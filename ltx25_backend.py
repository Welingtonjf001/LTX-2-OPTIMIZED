"""LTX-2.5 generation backend for the *_25 UIs.

Why this exists (and why the 2.5 UIs can't just reuse the 2.3 code path):
`ltx_pipelines` has no LTX-2.5 support -- no CLI for the split per-component
checkpoints, no Gemma4 text encoder in `ltx_core`, and no NADiffusionDecoder
for the 2.5 video VAE. The ComfyUI route DOES support 2.5 end to end (the
vendored ComfyUI core carries `comfy/ldm/lightricks/vae/na_diffusion_decoder.py`
and the LTXVideo custom node ships official 2.5 workflows), and it is the route
validated in this repo -- 6/6 screenplay prompts generated with video+audio.
See MEMORIAL.md, section "LTX-2.5".

So this module mirrors the role `gguf_backend.py` plays for the 2.3 GGUF path:
keep one ComfyUI server alive, patch the official 2.5 workflow with the UI's
parameters, submit it over the HTTP API, and hand back the produced mp4.

Known gaps in this first version (kept explicit rather than silently wrong):
  - Two-stage (2x latent upscale + refine) IS wired since 2026-08-24, but is
    opt-in: `two_stage=True`, `--two-stage`, or LTX25_TWO_STAGE=1. It is not
    derived from the 2.3 UIs' `--spatial-upsampler-path`, which they pass on
    every run -- keying off it would silently slow every existing render.
  - No LoRA support: the official single-stage 2.5 T2V graph has no LoRA loader
    node, so the 2.3 UIs' LoRA pickers do not carry over.
  - Progress is reported as elapsed wall time, not per-step percentage: the
    ComfyUI HTTP API only exposes a finished job through /history (live
    per-node progress needs the websocket channel, not wired here).
  - Audio is generated by the graph itself (T2A). `disable_audio=True` drops
    the audio track from the muxed output; it does not save the sampling cost.
"""
