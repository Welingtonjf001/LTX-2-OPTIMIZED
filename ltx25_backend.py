_BOOT_LOCK_PATH = os.path.join(ROOT, "logs", "comfyui_ltx25.boot.lock")
_BOOT_LOCK_STALE_S = 600  # mais que qualquer boot_timeout razoavel


@contextlib.contextmanager
def _boot_lock(wait_s: int = 300):
    """Mutex entre PROCESSOS para a decisao 'o servidor existe? inicio um?'.

    Sem isto, duas UIs abertas ao mesmo tempo podem cada uma concluir
    independentemente que a porta 8188 nao responde e tentar subir o
    ComfyUI -- dois processos disputando a mesma porta e a mesma VRAM. O
    `O_CREAT|O_EXCL` e atomico no Windows tambem: so um `open()` concorrente
    ganha o arquivo, os outros recebem FileExistsError.

    Nao bloqueia para sempre: se a espera estourar `wait_s`, segue sem o lock
    -- e o mesmo comportamento de antes de existir lock nenhum, nunca pior."""
    inicio = time.time()
    fd = None
    while True:
        try:
            fd = os.open(_BOOT_LOCK_PATH, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
            os.write(fd, f"{os.getpid()} {time.time()}".encode("ascii"))
            os.close(fd)
            break
        except FileExistsError:
            try:
                idade = time.time() - os.path.getmtime(_BOOT_LOCK_PATH)
            except OSError:
                idade = 0  # sumiu entre o check e agora; tenta de novo
            if idade > _BOOT_LOCK_STALE_S:
                # Lock orfao de um processo que morreu segurando-o.
                try:
                    os.remove(_BOOT_LOCK_PATH)
                except OSError:
                    pass
                continue
            if time.time() - inicio > wait_s:
                break  # desiste do lock, segue sem ele -- nunca pior que antes
            time.sleep(1)
    try:
        yield
    finally:
        try:
            os.remove(_BOOT_LOCK_PATH)
        except OSError:
            pass


def ensure_server(log_cb=None, boot_timeout: int = 300) -> None:
    """Start the ComfyUI server if it isn't already running. Idempotent."""
    global _server_proc, _server_log_handle
    if server_is_up():
        return
    os.makedirs(os.path.join(ROOT, "logs"), exist_ok=True)
    with _boot_lock():
        # Double-check: quem segurou o lock antes de nos pode ter acabado de
        # subir o servidor -- reconferir evita um segundo boot desnecessario.
        if server_is_up():
            return
        _ensure_server_locked(log_cb=log_cb, boot_timeout=boot_timeout)


def _ensure_server_locked(log_cb=None, boot_timeout: int = 300) -> None:
    global _server_proc, _server_log_handle

    def log(msg):
        _log(msg, log_cb)

    log("[ltx25] ComfyUI não está no ar; iniciando servidor (~1min)...")
    env = os.environ.copy()
    env.setdefault("CUDA_VISIBLE_DEVICES", "1")
    env.setdefault("HF_HUB_OFFLINE", "1")
    env.setdefault("PYTHONUNBUFFERED", "1")
    env.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")

    python_exe = os.path.join(ROOT, ".venv", "Scripts", "python.exe")
    logs_dir = os.path.join(ROOT, "logs")
    os.makedirs(logs_dir, exist_ok=True)
    _server_log_handle = open(os.path.join(logs_dir, "comfyui_ltx25.log"), "a", encoding="utf-8", buffering=1)
    try:
        # ATENCAO: isto so vale quando ESTE modulo sobe o servidor. Na cadeia de
        # decupagem quem sobe e o estagio dos stills, sem --cache-none, e este
        # ensure_server volta cedo -- ver comfy_launch_args em
        # script_pipeline/generate_storyboards.py.
        import sys as _sys
        if ROOT not in _sys.path:
            _sys.path.insert(0, ROOT)
        from script_pipeline.generate_storyboards import comfy_launch_args
        cmd = comfy_launch_args(python_exe, port=COMFY_PORT, cache_none=True,
                                extra=["--disable-auto-launch"])
        log("[ltx25] ComfyUI: " + " ".join(cmd[3:]))
        _server_proc = subprocess.Popen(
            cmd, cwd=COMFY_ROOT, env=env,
            stdout=_server_log_handle, stderr=subprocess.STDOUT,
        )
    except Exception:
        _server_log_handle.close()
        _server_log_handle = None
        raise

    import atexit
    atexit.register(shutdown_server)

    t0 = time.time()
    while time.time() - t0 < boot_timeout:
        if server_is_up():
            log(f"[ltx25] ComfyUI pronto em {time.time()-t0:.1f}s.")
            return
        if _server_proc.poll() is not None:
            rc = _server_proc.returncode
            shutdown_server()
            raise RuntimeError(f"ComfyUI encerrou durante o boot (exit code {rc}).")
        time.sleep(2)
    shutdown_server()
    raise RuntimeError(f"ComfyUI não respondeu em {boot_timeout}s.")


def shutdown_server() -> None:
    global _server_proc, _server_log_handle
    if _server_proc is not None and _server_proc.poll() is None:
        _server_proc.terminate()
        try:
            _server_proc.wait(timeout=15)
        except subprocess.TimeoutExpired:
            _server_proc.kill()
    _server_proc = None
    if _server_log_handle is not None:
        _server_log_handle.close()
        _server_log_handle = None


def _post_json(url, payload):
    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(url, data=data, headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return json.load(r)


def _get_json(url):
    with urllib.request.urlopen(url, timeout=120) as r:
        return json.load(r)


def base_api(two_stage: bool = False) -> dict:
    """Convert the official 2.5 workflow to API format once, then reuse.

    Needs a live server: the converter reads every node's schema from
    /object_info to map positional widget values onto input names.

    two_stage selects the refine graph -- see TWO_STAGE_* and stage_ids().
    """
    key = "two" if two_stage else "one"
    if _base_api_cache.get(key) is None:
        ensure_server()
        path = WORKFLOW_PATH_TWO_STAGE if two_stage else WORKFLOW_PATH
        ui = json.load(open(path, encoding="utf-8"))
        oi = wf_tool.fetch_object_info(COMFY_SERVER)
        api = wf_tool.convert(ui, oi)
        api = wf_tool.prune_to_output(api, SAVE_NODE_ID)
        ids = stage_ids(two_stage)
        expected = [N_POSITIVE, N_NEGATIVE, N_FPS, N_SECONDS, N_USE_IMAGE,
                    N_LATENT, N_SAVE, N_SEED, N_LOAD_IMAGE, N_RESIZE,
                    N_CREATE_VIDEO, N_SAMPLER, N_CFG_GUIDER, N_SIGMAS, N_CONCAT,
                    ids["unet"], ids["enhancer_clip"]]
        if two_stage:
            expected += [N2_UPSAMPLER, N2_IMG2VID, N2_SEED, N2_SIGMAS, N2_SAMPLER]
        missing = [n for n in expected if n not in api]
        if missing:
            raise RuntimeError(
                "O workflow oficial 2.5 mudou de estrutura: nós esperados ausentes "
                f"após a conversão: {missing}. Revise os ids em ltx25_backend.py."
            )
        _base_api_cache[key] = api
    return json.loads(json.dumps(_base_api_cache[key]))  # deep copy per call


def _format_exec_error(messages: list) -> str:
    """Turn ComfyUI's /history error payload into something readable.

    The raw payload is one long JSON line whose useful part -- the failing node
    and the DEEPEST traceback frames -- sits at the very end, so truncating the
    front of it (which is what a plain `json.dumps(...)[:3000]` does) throws away
    exactly the lines that name the tensor. Pull the fields out instead, and when
    the traceback has to be trimmed, keep the tail.
    """
    err = next((d for kind, d in messages if kind == "execution_error"), None)
    if err is None:
        return "Geração falhou:\n" + json.dumps(messages, ensure_ascii=False)[:3000]
    tb = "".join(err.get("traceback") or [])
    if len(tb) > 4000:
        tb = "... (topo do traceback omitido) ...\n" + tb[-4000:]
    return (
        f"Geração falhou no nó {err.get('node_id')} ({err.get('node_type')}):\n"
        f"{err.get('exception_type')}: {err.get('exception_message')}\n\n{tb}"
    )


